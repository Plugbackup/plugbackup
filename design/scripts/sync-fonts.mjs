// Copies the official IBM Plex woff2 subsets from node_modules into fonts/
// and generates fonts/fonts.css. The files are used unmodified (OFL 1.1).
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'fonts');

const families = [
  { pkg: '@ibm/plex-sans', prefix: 'IBMPlexSans', family: 'IBM Plex Sans', license: 'OFL-IBM-Plex-Sans.txt' },
  { pkg: '@ibm/plex-mono', prefix: 'IBMPlexMono', family: 'IBM Plex Mono', license: 'OFL-IBM-Plex-Mono.txt' },
];
const weights = [
  ['Regular', 400],
  ['Medium', 500],
  ['SemiBold', 600],
];
const subsets = ['Cyrillic', 'Latin1', 'Latin2', 'Pi'];

await mkdir(out, { recursive: true });

let css = `/* Generated by scripts/sync-fonts.mjs. Fonts: IBM Plex, SIL OFL 1.1, see OFL-*.txt. */\n`;

for (const { pkg, prefix, family, license } of families) {
  const pkgDir = join(root, 'node_modules', pkg);
  // The licence text is copied as is, only trailing whitespace is trimmed (repository lint).
  const licenseText = (await readFile(join(pkgDir, 'LICENSE.txt'), 'utf8')).replace(/[ \t]+$/gm, '').replace(/\s*$/, '\n');
  await writeFile(join(out, license), licenseText);

  for (const [name, weight] of weights) {
    const splitDir = join(pkgDir, 'fonts', 'split', 'woff2');
    const source = await readFile(join(splitDir, `${prefix}-${name}.css`), 'utf8');
    const ranges = new Map();
    for (const block of source.matchAll(/@font-face\s*{([^}]*)}/g)) {
      const file = block[1].match(/url\(["']?([^"')]+\.woff2)["']?\)/)?.[1];
      const range = block[1].match(/unicode-range:\s*([^;}\n]+)/)?.[1]?.trim();
      if (file && range) ranges.set(file, range);
    }

    for (const subset of subsets) {
      const file = `${prefix}-${name}-${subset}.woff2`;
      const range = ranges.get(file);
      if (!range) throw new Error(`No unicode-range for ${file}`);
      await copyFile(join(splitDir, file), join(out, file));
      css += `
@font-face {
  font-family: '${family}';
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url('${file}') format('woff2');
  unicode-range: ${range};
}
`;
    }
  }
}

await writeFile(join(out, 'fonts.css'), css);
console.log(`fonts: ${families.length * weights.length * subsets.length} woff2 files, fonts.css`);
