"""Сроки жизненного цикла клиента (секунды)."""

DAY = 24 * 3600

# Бета: раз в 30 дней просим нажать «Я ещё пользуюсь», через 7 дней без ответа блокируем.
BETA_CONFIRM_PERIOD_S = 30 * DAY
BETA_GRACE_S = 7 * DAY
# Бета без присланного ключа: инвайт сгорает.
PENDING_TTL_S = 7 * DAY

# Платные: после окончания периода без продления ещё 3 дня до блокировки.
PAID_GRACE_S = 3 * DAY
# Заблокированного клиента удаляем через 14 дней.
SUSPENDED_TTL_S = 14 * DAY

# За сколько до окончания предупреждаем (только если продления не будет).
WARN_BEFORE_S = (3 * DAY, 1 * DAY)
# Перед блокировкой и перед удалением предупреждаем за сутки.
NOTICE_BEFORE_ACTION_S = 1 * DAY
